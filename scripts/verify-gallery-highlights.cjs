const assert = require('node:assert/strict')
const { chromium } = require('playwright-core')
const base = process.env.GALLERY_PREVIEW_URL || 'http://127.0.0.1:8788'

async function main() {
  const browser = await chromium.launch({ executablePath: process.env.CHROME_PATH || '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome', headless: true })
  try {
    const page = await browser.newPage({ viewport: { width: 1440, height: 1000 }, reducedMotion: 'reduce', colorScheme: 'dark' })
    const errors = [], models = []
    page.on('pageerror', error => errors.push(error.message))
    page.on('request', request => { if (request.url().includes('.glb')) models.push(request.url()) })
    await page.goto(`${base}/gallery`)
    const droplet = page.locator('main a[href="/gallery/droplet"]')
    assert.equal(await droplet.count(), 1)
    for (const link of [droplet, page.locator('main a[href="/gallery/cars"]')]) {
      await link.locator('img').evaluate(img => img.decode())
      const image = await link.locator('img').boundingBox()
      assert(Math.abs(image.width / image.height - 4 / 3) < .03, 'Grid thumbnails fill their 4:3 tiles')
    }
    const carImage = page.locator('main a[href="/gallery/cars"] img')
    const operationsImage = page.locator('main a[href="/p/joelops/demo"] img')
    assert.match(await carImage.evaluate(img => img.currentSrc), /cars-dark\.webp/)
    assert.match(await operationsImage.evaluate(img => img.currentSrc), /global-operations-demo-dark\.webp/)
    await page.emulateMedia({ colorScheme: 'light' })
    await page.waitForFunction(() => document.querySelector('a[href="/gallery/cars"] img')?.currentSrc.includes('/cars.webp'))
    assert.match(await operationsImage.evaluate(img => img.currentSrc), /global-operations-demo\.webp/)
    assert.equal(await page.locator('main video').count(), 0, 'Reduced motion leaves thumbnails still')
    await page.emulateMedia({ colorScheme: 'dark' })
    assert.equal(models.length, 0, 'Gallery cards do not load vehicle models')
    await page.screenshot({ path: '/private/tmp/jh-gallery-desktop.png', fullPage: true })
    await page.locator('main a[href="/gallery/cars"]').click()
    const experience = page.frameLocator('dialog iframe')
    const ready = () => page.waitForFunction(() => {
      const next = document.querySelector('dialog iframe')?.contentDocument?.querySelector('[aria-label="Next vehicle"]')
      return next && !next.disabled
    }, null, { timeout: 60000 })
    await ready()
    assert.equal(await experience.locator('main canvas').count(), 1)
    assert(models.some(url => url.includes('4runner.glb')))
    assert(!models.some(url => url.includes('mclaren.glb')), 'Load the next vehicle only when requested')
    assert.equal(await experience.getByRole('button', { name: 'Dark', exact: true }).count(), 0, 'Vehicle uses the system theme')
    await experience.getByText('Vehicle controls', { exact: true }).click()
    await experience.getByLabel('Headlights', { exact: true }).selectOption('off')
    assert.equal(await experience.getByLabel('Headlights', { exact: true }).inputValue(), 'off')
    await experience.getByRole('button', { name: 'Front', exact: true }).click()
    await experience.getByRole('button', { name: 'Quarter', exact: true }).click()
    await experience.getByRole('button', { name: 'Wireframe', exact: true }).click()
    assert.equal(await experience.getByRole('button', { name: 'Wireframe', exact: true }).getAttribute('aria-pressed'), 'true')
    await experience.getByRole('button', { name: 'Wireframe', exact: true }).click()
    assert(await experience.getByRole('button', { name: 'Auto rotate', exact: true }).isDisabled())
    await experience.getByRole('button', { name: 'Next vehicle' }).click(); await ready()
    assert.match(await experience.getByRole('navigation', { name: 'Choose a vehicle' }).innerText(), /McLaren MP4\/5/)
    assert(models.some(url => url.includes('mclaren.glb')))
    assert(!models.some(url => url.includes('lancia.glb')))
    await experience.getByRole('button', { name: 'Previous vehicle' }).click(); await ready()
    await page.emulateMedia({ colorScheme: 'light' })
    await experience.getByText('Vehicle controls', { exact: true }).click()
    await page.screenshot({ path: '/private/tmp/jh-cars-desktop.png' })
    for (const [width, height] of [[390, 844], [320, 568], [844, 390]]) {
      await page.setViewportSize({ width, height })
      await page.waitForTimeout(200)
      assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'No horizontal page overflow')
      await experience.getByRole('button', { name: 'Next vehicle' }).scrollIntoViewIfNeeded()
      assert(await experience.getByRole('button', { name: 'Next vehicle' }).isVisible())
      if (width === 390) await page.screenshot({ path: '/private/tmp/jh-cars-mobile.png', fullPage: true })
    }
    await page.goto(`${base}/gallery`)
    assert.equal(await page.locator('main canvas').count(), 0)
    await page.goto(`${base}/`)
    assert(await page.locator('.home-project[href="/gallery/droplet"]').count() > 0)
    assert(await page.locator('.home-project[href="/gallery/cars"]').count() > 0)
    assert.deepEqual(errors, [])

    const failed = await browser.newPage()
    await failed.route('**/assets/about/garage/runtime.js*', route => route.abort())
    await failed.goto(`${base}/gallery/cars`)
    await failed.locator('main').getByRole('alert').waitFor()
    assert(await failed.getByRole('button', { name: 'Try again' }).isVisible())
    await failed.locator('img[alt="Toyota 4Runner in the vehicle playground"]').evaluate(img => img.decode())
    console.log('Gallery: image previews, external destination, lazy models, vehicle switching, views, lighting, wireframe, reduced motion, responsive layouts, homepage entries and failure fallback passed.')
  } finally { await browser.close() }
}
main().catch(error => { console.error(error); process.exitCode = 1 })
