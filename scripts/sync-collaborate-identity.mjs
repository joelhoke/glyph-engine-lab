#!/usr/bin/env node

import { createHash } from 'node:crypto'
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const projectRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const sourcePath = resolve(projectRoot, 'knowledge/identity/identity.md')
const outputPath = resolve(projectRoot, 'functions/lib/generated/collaborateIdentity.ts')
const checkOnly = process.argv.includes('--check')

function parseCanonicalIdentity(source) {
  const normalized = source.replace(/\r\n/g, '\n')
  const match = normalized.match(/^---\n([\s\S]*?)\n---\n+([\s\S]+)$/)
  if (!match) throw new Error('identity.md must begin with a YAML-style metadata block')

  const metadata = {}
  for (const line of match[1].split('\n')) {
    const separator = line.indexOf(':')
    if (separator < 1) throw new Error(`Invalid identity metadata line: ${line}`)
    const key = line.slice(0, separator).trim()
    const value = line.slice(separator + 1).trim()
    if (!value) throw new Error(`Identity metadata ${key} cannot be empty`)
    metadata[key] = value
  }

  for (const key of ['version', 'updated', 'status', 'audience']) {
    if (!metadata[key]) throw new Error(`identity.md metadata is missing ${key}`)
  }
  if (!/^\d+\.\d+$/.test(metadata.version))
    throw new Error('identity.md version must use <major>.<minor> format')
  if (!/^\d{4}-\d{2}-\d{2}$/.test(metadata.updated))
    throw new Error('identity.md updated must use YYYY-MM-DD format')
  if (metadata.status !== 'evolving' && metadata.status !== 'stable')
    throw new Error('identity.md status must be evolving or stable')
  if (metadata.audience !== 'public-agent')
    throw new Error('identity.md audience must remain public-agent')

  const markdown = match[2].trim()
  if (!markdown.startsWith('# Joel Hoke — Identity'))
    throw new Error('identity.md must begin with the canonical title')
  if (markdown.length < 500) throw new Error('identity.md is unexpectedly short')

  return { metadata, markdown }
}

function renderModule(identity) {
  const digest = createHash('sha256').update(identity.markdown).digest('hex')
  return `// AUTO-GENERATED by scripts/sync-collaborate-identity.mjs.\n// Edit knowledge/identity/identity.md, then run npm run identity:sync.\n\nexport const COLLABORATE_IDENTITY_VERSION = ${JSON.stringify(identity.metadata.version)}\nexport const COLLABORATE_IDENTITY_UPDATED = ${JSON.stringify(identity.metadata.updated)}\nexport const COLLABORATE_IDENTITY_STATUS = ${JSON.stringify(identity.metadata.status)}\nexport const COLLABORATE_IDENTITY_SHA256 = ${JSON.stringify(digest)}\nexport const COLLABORATE_IDENTITY_MARKDOWN = ${JSON.stringify(identity.markdown)}\n`
}

const source = readFileSync(sourcePath, 'utf8')
const expected = renderModule(parseCanonicalIdentity(source))
const current = existsSync(outputPath) ? readFileSync(outputPath, 'utf8') : null

if (checkOnly) {
  if (current !== expected) {
    console.error('Canonical identity bundle is stale. Run: npm run identity:sync')
    process.exit(1)
  }
  console.log('PASS: canonical identity bundle is current')
  process.exit(0)
}

if (current === expected) {
  console.log('Canonical identity bundle is already current')
  process.exit(0)
}

mkdirSync(dirname(outputPath), { recursive: true })
writeFileSync(outputPath, expected)
console.log('Updated functions/lib/generated/collaborateIdentity.ts')
