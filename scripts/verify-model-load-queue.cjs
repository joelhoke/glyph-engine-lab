const assert = require('node:assert/strict')
const { execFileSync } = require('node:child_process')
const path = require('node:path')
const out = path.resolve('tmp-verify-model-load-queue')
execFileSync(path.resolve('node_modules/.bin/tsc'), ['components/home/modelLoadQueue.ts', '--outDir', out, '--module', 'commonjs', '--target', 'es2020', '--skipLibCheck'], { stdio: 'inherit' })
const { createModelLoadQueue, modelLoadPriority } = require(path.join(out, 'modelLoadQueue.js'))
const tasks = [], starts = []
const queue = createModelLoadQueue(2, callback => tasks.push(callback))
const flush = () => { while (tasks.length) tasks.shift()() }
const hidden = queue.enqueue(-1, () => starts.push('hidden'))
const background = queue.enqueue(5, () => starts.push('background'))
const selected = queue.enqueue(40, () => starts.push('selected'))
const primary = queue.enqueue(15, () => starts.push('primary'))
flush()
assert.deepEqual(starts, ['selected', 'primary'], 'highest priorities start first, bounded to two')
hidden.setPriority(50)
selected.finish(); selected.finish(); flush()
assert.deepEqual(starts, ['selected', 'primary', 'hidden'], 'interaction promotes queued work; finishing twice does not free two slots')
primary.finish(); flush()
assert.deepEqual(starts, ['selected', 'primary', 'hidden', 'background'])
hidden.finish(); background.finish(); flush()
const removed = queue.enqueue(100, () => starts.push('removed'))
removed.finish(); flush()
assert(!starts.includes('removed'), 'unmounted pending work never starts')
const paused = queue.enqueue(20, () => starts.push('resumed'))
paused.setPriority(-1); flush()
assert(!starts.includes('resumed'), 'visibility can pause work before it starts')
paused.setPriority(10); flush()
assert.equal(starts.at(-1), 'resumed', 'visibility resumes work without a new ticket')
assert.equal(modelLoadPriority(false, false, 'hero', 'work'), -1)
assert(modelLoadPriority(true, false, 'section', 'work') > modelLoadPriority(true, false, 'hero', 'notebook'), 'visible destination takes precedence over idle hero')
assert(modelLoadPriority(true, true, 'hero', 'work') > modelLoadPriority(true, false, 'hero', 'notebook'), 'selected mobile object has priority')
console.log('PASS: model queue concurrency, priority, promotion, cancellation and visibility')
